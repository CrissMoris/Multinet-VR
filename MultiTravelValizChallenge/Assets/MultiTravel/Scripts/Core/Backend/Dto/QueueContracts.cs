using System;
using Newtonsoft.Json;

namespace MultiTravel.Core.Backend
{
    /// <summary>
    /// One participant waiting in the web registration queue (<c>list_waiting_participants</c>). Carries no contact data:
    /// the queue is shown on the operator screen, which is mirrored to the stand TV.
    /// </summary>
    public sealed class WaitingParticipant
    {
        [JsonProperty("participant_id")]
        public Guid ParticipantId { get; set; }

        /// <summary>First name + last initial ("Ayşe Y.").</summary>
        [JsonProperty("display_name")]
        public string DisplayName { get; set; }

        /// <summary>"female" / "male" (product set chosen on the registration page).</summary>
        [JsonProperty("gender")]
        public string Gender { get; set; }

        [JsonProperty("waiting_since")]
        public DateTime WaitingSince { get; set; }
    }

    /// <summary>Full participant record handed to the station by <c>claim_participant</c> (not displayed).</summary>
    public sealed class ClaimedParticipant
    {
        [JsonProperty("participant_id")]
        public Guid ParticipantId { get; set; }

        /// <summary>Session id generated by the server at web registration; results are submitted under it.</summary>
        [JsonProperty("client_session_id")]
        public Guid ClientSessionId { get; set; }

        [JsonProperty("first_name")]
        public string FirstName { get; set; }

        [JsonProperty("last_name")]
        public string LastName { get; set; }

        [JsonProperty("title")]
        public string Title { get; set; }

        [JsonProperty("company")]
        public string Company { get; set; }

        [JsonProperty("location")]
        public string Location { get; set; }

        [JsonProperty("phone")]
        public string Phone { get; set; }

        [JsonProperty("email")]
        public string Email { get; set; }

        [JsonProperty("gender")]
        public string Gender { get; set; }

        [JsonProperty("consent_accepted")]
        public bool? ConsentAccepted { get; set; }

        [JsonProperty("consent_version")]
        public string ConsentVersion { get; set; }
    }

    /// <summary>Response of <c>release_participant</c> / <c>remove_from_queue</c>.</summary>
    public sealed class QueueAck
    {
        [JsonProperty("ok")]
        public bool Ok { get; set; }
    }

    public sealed class ListWaitingRequest
    {
        [JsonProperty("p_event_slug")]
        public string EventSlug { get; set; }

        [JsonProperty("p_access_code")]
        public string AccessCode { get; set; }

        [JsonProperty("p_limit")]
        public int Limit { get; set; }
    }

    public sealed class ClaimParticipantRequest
    {
        [JsonProperty("p_event_slug")]
        public string EventSlug { get; set; }

        [JsonProperty("p_access_code")]
        public string AccessCode { get; set; }

        [JsonProperty("p_participant_id")]
        public Guid ParticipantId { get; set; }

        [JsonProperty("p_station_id")]
        public string StationId { get; set; }
    }

    public sealed class QueueParticipantRequest
    {
        [JsonProperty("p_event_slug")]
        public string EventSlug { get; set; }

        [JsonProperty("p_access_code")]
        public string AccessCode { get; set; }

        [JsonProperty("p_participant_id")]
        public Guid ParticipantId { get; set; }
    }
}
